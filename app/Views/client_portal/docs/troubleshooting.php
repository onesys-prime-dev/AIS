    <h2>Troubleshooting Playbook</h2>
    <p><strong>Purpose:</strong> Provide quick, scannable fixes for common problems.</p>
    <p><strong>Audience:</strong> End users and support staff.</p>

    <h3>Common symptoms</h3>
    <h4>Can't upload attachments</h4>
    <p>Cause: File size or type restriction.</p>
    <p>Fix: Ensure file is under the allowed size and of permitted type (PDF, JPG, PNG). Try compressing the file or use the import tool.</p>

    <h4>Slow page loads</h4>
    <p>Cause: Network latency, large attachments, or cache problems.</p>
    <p>Fix: Clear browser cache, check network, and avoid uploading very large files. If problem persists, capture a HAR file and provide it to support.</p>

    <h3>Escalation</h3>
    <ol>
        <li>Collect user info, screenshots, and steps to reproduce.</li>
        <li>Attempt suggested fixes from this playbook.</li>
        <li>If unresolved, escalate to L2 with collected artifacts.</li>
    </ol>

