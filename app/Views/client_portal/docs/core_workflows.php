    <h2>Core Workflows</h2>
    <p><strong>Purpose:</strong> Step-by-step guides for the most-used transactions in OTIS.</p>
    <p><strong>Audience:</strong> Regular users and managers.</p>

    <h3>Top workflows (examples)</h3>
    <h4>1. Submit an Expense</h4>
    <ol>
        <li>Open the Expenses module and click "New Request".</li>
        <li>Fill required fields: Amount, Date, Category, Attachment.</li>
        <li>Click "Submit". Approvers will be notified automatically.</li>
    </ol>

    <h4>2. Approve a Request (Manager)</h4>
    <ol>
        <li>Go to Approvals &gt; Pending.</li>
        <li>Review details and attachments, then select Approve or Reject.</li>
    </ol>

    <h3>Expected results</h3>
    <p>Transactions proceed through defined status states and are auditable.</p>

    <h3>Common issues & fixes</h3>
    <ul>
        <li>Missing attachment: Re-open the request and attach the missing file.</li>
        <li>Approval notifications not received: Check notification settings and spam folder.</li>
    </ul>

