    <h2>Operational Knowledge Base</h2>

    <h3>Why hasn't my payroll been generated yet?</h3>
    <p><strong>Cause:</strong> The payroll cutoff for that period hasn't been processed and finalized by Payroll Staff yet.</p>
    <p><strong>Resolution:</strong> Check with Payroll Staff on the cutoff schedule; payslips only appear once payroll for that period is released.</p>

    <h3>Why isn't my overtime/undertime showing up?</h3>
    <p><strong>Cause:</strong> The request is still pending approval, or wasn't submitted before the cutoff.</p>
    <p><strong>Resolution:</strong> Check the request's status under Requests. If it's still Pending, follow up with whoever reviews requests for you (Payroll Staff, HR Admin, or your Team Head).</p>

    <h3>Why can't I see my payslip?</h3>
    <p><strong>Cause:</strong> Your payslip for that period hasn't been sent yet — payroll saves payslips as drafts first and sends them later.</p>
    <p><strong>Resolution:</strong> It appears (and is emailed to you) once Payroll Staff sends it — right away, or automatically on the scheduled salary day. If the salary day has passed and it's still missing, contact Payroll Staff.</p>

    <h3>Why did my employee CSV import fail?</h3>
    <p><strong>Cause:</strong> Missing required columns, or an invalid/duplicate employee ID or email in the file.</p>
    <p><strong>Resolution:</strong> Re-check the file against the required template columns and fix any duplicate or missing values before re-uploading.</p>

    <h3>Why won't my announcement attachment upload?</h3>
    <p><strong>Cause:</strong> Unsupported file type, or the file exceeds the 5&nbsp;MB per-file limit.</p>
    <p><strong>Resolution:</strong> Only images, PDF, DOC, and DOCX files are accepted, up to 6 files per announcement.</p>

    <h3>Why don't I see a notification I was just told about?</h3>
    <p><strong>Cause:</strong> The bell dropdown loads notifications when the page loads; a brand-new announcement or approval published seconds ago may not appear until the page refreshes or the next periodic check.</p>
    <p><strong>Resolution:</strong> Refresh the page. The unread badge count updates automatically once you view or dismiss notifications.</p>

    <h3>Why does the "Edit announcement" option not appear for me?</h3>
    <p><strong>Cause:</strong> Only Payroll Staff can edit announcements, and only the person who originally published it.</p>
    <p><strong>Resolution:</strong> Ask the original author to make the edit, or have them delete it and re-publish.</p>
