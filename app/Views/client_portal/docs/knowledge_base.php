    <h2>Operational Knowledge Base</h2>

    <h3>Why was my payroll not generated?</h3>
    <p><strong>Cause:</strong> Payroll period has not been finalized.</p>
    <p><strong>Resolution:</strong> Complete payroll review and approval.</p>

    <h3>Why is overtime not reflected?</h3>
    <p><strong>Cause:</strong> OT request is pending approval.</p>
    <p><strong>Resolution:</strong> Verify request status with your supervisor.</p>

    <h3>Why can't I access my payslip?</h3>
    <p><strong>Cause:</strong> Payroll is still in Draft or Pending Review.</p>
    <p><strong>Resolution:</strong> Wait until payroll is finalized.</p>

    <h3>Why was my bookkeeping upload rejected?</h3>
    <p><strong>Cause:</strong> Incorrect file format.</p>
    <p><strong>Resolution:</strong> Use the latest Excel template.</p>

    <h3>Why can't I upload documents?</h3>
    <p><strong>Cause:</strong> File exceeds size limit or unsupported format.</p>
    <p><strong>Resolution:</strong> Upload PDF, JPG, or PNG files only.</p>

    <h3>Why are my financial reports empty?</h3>
    <p><strong>Cause:</strong> No transactions exist for the selected period.</p>
    <p><strong>Resolution:</strong> Verify filters and accounting entries.</p>
