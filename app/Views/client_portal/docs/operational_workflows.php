    <h2>Operational Workflows</h2>

    <h3>Daily Attendance</h3>
    <ol>
        <li>Employee clocks in from the Dashboard.</li>
        <li>Breaks can be started/ended from the same screen.</li>
        <li>Employee clocks out at the end of the shift.</li>
        <li>If clocking out early or after scheduled hours, the system may prompt for a reason (undertime/overtime).</li>
        <li>Entries appear in the Daily Time Log and Attendance History.</li>
    </ol>

    <h3>Overtime / Undertime / Leave Requests</h3>
    <ol>
        <li>Employee submits a request with a date, type, and reason.</li>
        <li>An approval code may be generated by payroll/HR staff and shared with the employee to speed up submission.</li>
        <li>Payroll Staff, HR Admin, or a Team Head (for their own team) reviews and approves or denies it.</li>
        <li>Approved requests are reflected in attendance and, where relevant, in payroll computation.</li>
    </ol>

    <h3>Payroll Processing</h3>
    <p>All done from the Payroll section, which has 6 tabs:</p>
    <ol>
        <li><strong>Payroll Output</strong> — Raw Sheet, Register, Payslip, History, and Bank File live here: the cutoff's attendance and approved requests are pulled together, reviewed, and turned into payslips and a bank disbursement file.</li>
        <li><strong>Payroll Status</strong> — Payroll Staff reviews the figures and updates the status as it moves toward release.</li>
        <li><strong>Generate Payslip</strong> — payslips are produced from the finalized payroll and become visible to employees.</li>
        <li><strong>13th Month &amp; Annualization</strong> — computed and processed separately when due, not part of a regular cutoff.</li>
        <li><strong>Payroll Settings</strong> — cutoff schedules, rates, and related configuration live here.</li>
        <li><strong>Audit Log</strong> — every payroll action above (creation, rate changes, status changes, payslip generation/edits/sending) is recorded here automatically.</li>
    </ol>

    <h3>Employee Loans</h3>
    <p>
        Loans are entirely staff-managed — there's no employee-facing "apply
        for a loan" screen, and employees don't have direct access to the
        Loan Management tab to check status themselves.
    </p>
    <ol>
        <li>An employee requests a loan outside the system (in person, via a help request, etc.).</li>
        <li>Payroll Staff records it under Employee &gt; Loan Management, setting the terms and repayment schedule.</li>
        <li>Repayments are typically deducted through payroll — check with Payroll Staff for your current loan status.</li>
    </ol>

    <h3>Announcements</h3>
    <ol>
        <li>Payroll Staff creates an announcement — title, category, audience (all / payroll staff / a specific department), priority, and an optional publish/expiry window.</li>
        <li>Attachments can be added (images, PDF, DOC/DOCX).</li>
        <li>Once published, it appears in the notification bell for everyone in its audience.</li>
        <li>The original author can edit or delete it later; other payroll staff can delete but not edit someone else's announcement.</li>
    </ol>

    <h3>Help Requests</h3>
    <ol>
        <li>Anyone can submit a help request from the Help Centre's contact form.</li>
        <li>Payroll Staff sees all help requests and can update their status (Open, In Progress, Resolved, Closed) and add a response.</li>
        <li>Employees see and track only their own submitted requests.</li>
    </ol>
