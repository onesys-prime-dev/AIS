    <h2>Operational Workflows</h2>

    <h3>Payroll Processing Workflow</h3>

    <ol>
        <li>Employees record attendance.</li>
        <li>Employees submit OT, UT, and Leave Requests.</li>
        <li>Payroll Staff reviews requests.</li>
        <li>System computes payroll.</li>
        <li>Payroll Staff reviews preliminary payroll.</li>
        <li>Payroll is finalized.</li>
        <li>Payslips are generated and emailed.</li>
        <li>Audit trail is archived.</li>
    </ol>

    <h3>Monthly Bookkeeping Workflow</h3>

    <ol>
        <li>Client uploads accounting templates.</li>
        <li>System validates files.</li>
        <li>Accounting Staff reviews transactions.</li>
        <li>Tax rules are applied.</li>
        <li>Financial statements are generated.</li>
        <li>Managing Accountant approves final books.</li>
    </ol>

    <h3>Bank Reconciliation Workflow</h3>

    <ol>
        <li>Upload Bank CSV.</li>
        <li>System suggests transaction matches.</li>
        <li>Accounting Staff confirms matches.</li>
        <li>Unmatched items are investigated.</li>
        <li>Reconciliation report is generated.</li>
    </ol>

    <h3>Tax Compliance Workflow</h3>

    <ol>
        <li>System calculates tax obligations.</li>
        <li>Tax forms are prepared.</li>
        <li>Deadlines are monitored.</li>
        <li>Reports are reviewed.</li>
        <li>Compliance submissions are completed.</li>
    </ol>
