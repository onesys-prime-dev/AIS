    <h2>Support & Escalation</h2>
    <p><strong>Purpose:</strong> How to contact support, what information to provide, and SLA expectations.</p>
    <p><strong>Audience:</strong> All users.</p>

    <h3>Support channels</h3>
    <ul>
        <li>In-app help form (this page)</li>
        <li>Email: support@ais.local</li>
        <li>Phone: +63 2 5555 0000 (business hours)
        </ul>

    <h3>What to include in a ticket</h3>
    <ul>
        <li>Steps to reproduce</li>
        <li>Screenshots or screencast</li>
        <li>User role and affected account IDs</li>
        <li>Timestamp and timezone</li>
    </ul>

    <h3>SLA targets</h3>
    <ul>
        <li>P1 (system down): 1 hour response</li>
        <li>P2 (major feature broken): 4 hour response</li>
        <li>P3 (minor): 1 business day response</li>
    </ul>

