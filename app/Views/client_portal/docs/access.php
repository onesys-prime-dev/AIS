    <h2>Access & Login Guide</h2>
    <p><strong>Purpose:</strong> Describe how users gain access, recover accounts, and common access-related tasks.</p>
    <p><strong>Audience:</strong> All users (employees, managers, admins).</p>
    <h3>Prerequisites</h3>
    <ul>
        <li>Valid company email address</li>
        <li>Internet access and supported browsers</li>
    </ul>
    <h3>Steps</h3>
    <ol>
        <li>Go to the login page and enter your company email.</li>
        <li>Enter the temporary password sent by IT, then set a new password.</li>
        <li>If you forgot your password, use the "Forgot password" link and follow the email instructions.</li>
        <li>For multi-factor authentication (MFA) setup, follow the prompts on first sign-in.</li>
    </ol>
    <h3>Expected result</h3>
    <p>User can sign in and access permitted areas matching their role.</p>
    <h3>Common issues & fixes</h3>
    <ul>
        <li>Login fails: Verify email spelling and check spam for the registration email.</li>
        <li>No MFA code: Confirm the authenticator app time sync or contact IT for reset.</li>
    </ul>
