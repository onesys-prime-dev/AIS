    <h2>User Role Guides</h2>

    <p>Access is controlled per person, based on which group your account belongs to.</p>

    <h3>Employee</h3>
    <ul>
        <li>Record Time In and Time Out, and log breaks</li>
        <li>Submit Overtime, Undertime, and Leave requests</li>
        <li>View attendance history and daily time log</li>
        <li>View and download own payslips</li>
        <li>View own announcements and submit help requests</li>
    </ul>
    <p>
        Loans are not self-service for this role — see Operational
        Workflows &gt; Employee Loans.
    </p>

    <h3>Client Payroll Staff</h3>
    <p>Everything an Employee can do, plus:</p>
    <ul>
        <li>Review and approve/deny attendance-related requests</li>
        <li>Manage employee records (create, edit, import/export)</li>
        <li>Run payroll: register, cutoffs, 13th-month pay, and generate payslips</li>
        <li>Review the payroll audit log</li>
        <li>Approve or decline loan applications</li>
        <li>Publish, edit, and delete announcements</li>
        <li>Respond to help requests submitted by employees</li>
        <li>Manage company branding/customization</li>
    </ul>

    <h3>HR Admin</h3>
    <ul>
        <li>Manage employee records</li>
        <li>Review requests and generate request approval codes</li>
        <li>Review attendance</li>
        <li>Publish announcements</li>
    </ul>

    <h3>Team Head</h3>
    <ul>
        <li>Review attendance and requests for their explicitly assigned team members only — not the whole company</li>
    </ul>

    <h3>Admin / Superadmin</h3>
    <ul>
        <li>Everything Client Payroll Staff can do</li>
        <li>Manage user accounts and role assignments</li>
        <li>Superadmin has unrestricted access to every module and permission</li>
    </ul>
</div>
