    <h2>User Role Guides</h2>

    <h3>Employee</h3>
    <ul>
        <li>Record Time In and Time Out</li>
        <li>Submit OT, UT, and Leave Requests</li>
        <li>View Attendance History</li>
        <li>Access Payslips</li>
        <li>Upload Personal Documents</li>
    </ul>

    <h3>Client Payroll Staff</h3>
    <ul>
        <li>Review Employee Attendance</li>
        <li>Approve Employee Requests</li>
        <li>Run Payroll Computation</li>
        <li>Generate Payslips</li>
        <li>Finalize Payroll</li>
        <li>Report Payroll Issues</li>
    </ul>

    <h3>Accounting Staff</h3>
    <ul>
        <li>Maintain Accounting Records</li>
        <li>Manage Bookkeeping Entries</li>
        <li>Perform Bank Reconciliation</li>
        <li>Generate Financial Statements</li>
        <li>Manage Tax Compliance</li>
    </ul>

    <h3>Managing Accountant</h3>
    <ul>
        <li>Approve Payroll and Financial Reports</li>
        <li>Review Audit Logs</li>
        <li>Assign Issue Tickets</li>
        <li>Monitor Compliance Deadlines</li>
    </ul>

    <h3>Administrator</h3>
    <ul>
        <li>Manage User Accounts</li>
        <li>Assign Permissions</li>
        <li>Manage System Configuration</li>
        <li>Override Transactions</li>
        <li>Monitor System Activities</li>
    </ul>
</div>